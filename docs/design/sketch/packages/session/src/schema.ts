// @kurumi/session/schema
// Replaces nanoclaw's per-session inbound.db / outbound.db. Both directions live in kurumi.db; the container
// reaches them only through the Agent Port (session.channel.* procedures). No SQLite file crosses VirtioFS.
import { agentGroup } from '@kurumi/agent/schema'
import { messagingGroup } from '@kurumi/chat/schema'
import { blob, index, integer, primaryKey, sqliteTable, text, uniqueIndex } from 'drizzle-orm/sqlite-core'
import { sql } from 'drizzle-orm'

export const session = sqliteTable(
  'session',
  {
    id: text('id').primaryKey(), // ses-<uuidv7>
    agentGroupId: text('agent_group_id')
      .notNull()
      .references(() => agentGroup.id, { onDelete: 'cascade' }),
    /** Bound Chat. null for task sessions and agent-shared sessions without a chat. */
    messagingGroupId: text('messaging_group_id').references(() => messagingGroup.id, { onDelete: 'set null' }),
    threadId: text('thread_id'),
    mode: text('mode', { enum: ['shared', 'per-thread', 'agent-shared', 'task'] }).notNull(),
    status: text('status', { enum: ['active', 'closed'] }).notNull(),
    lastActiveAt: integer('last_active_at', { mode: 'timestamp_ms' }).notNull(),
    createdAt: integer('created_at', { mode: 'timestamp_ms' }).notNull(),
  },
  (t) => [uniqueIndex('session_key').on(t.agentGroupId, t.messagingGroupId, t.threadId, t.mode)],
)

/** Host → agent. Written only by the host. Handed to exactly one container incarnation at a time. */
export const inboundMessage = sqliteTable(
  'inbound_message',
  {
    id: text('id').primaryKey(), // `<platformMsgId>:<agentGroupId>` for chat, uuidv7 otherwise
    sessionId: text('session_id')
      .notNull()
      .references(() => session.id, { onDelete: 'cascade' }),
    seq: integer('seq').notNull(), // per-session monotonic, host-assigned; the agent's message reference
    kind: text('kind', { enum: ['chat', 'task', 'system', 'echo', 'answer'] }).notNull(),
    /** false = Accumulate: context only, never wakes. */
    trigger: integer('trigger', { mode: 'boolean' }).notNull(),
    status: text('status', { enum: ['pending', 'processing', 'completed', 'failed', 'cancelled'] }).notNull(),
    /** The container incarnation that pulled it. Reaping that container returns its rows to pending. */
    claimedBy: text('claimed_by'),
    processAfter: integer('process_after', { mode: 'timestamp_ms' }),
    tries: integer('tries').notNull().default(0),
    content: text('content', { mode: 'json' }).notNull(),
    createdAt: integer('created_at', { mode: 'timestamp_ms' }).notNull(),
  },
  (t) => [
    uniqueIndex('inbound_seq').on(t.sessionId, t.seq),
    index('inbound_due').on(t.status, t.processAfter),
  ],
)

/**
 * Agent → host. Written only by the host, on the agent's behalf, from session.channel.post.
 * `id` is generated by the runner (uuidv7) so a retried post after a host restart is a no-op.
 */
export const outboundMessage = sqliteTable(
  'outbound_message',
  {
    id: text('id').primaryKey(),
    sessionId: text('session_id')
      .notNull()
      .references(() => session.id, { onDelete: 'cascade' }),
    seq: integer('seq').notNull(),
    inReplyTo: text('in_reply_to'),
    /** Destination local name; null = the Bound Chat. Resolved to a platform target at delivery. */
    to: text('to'),
    kind: text('kind', { enum: ['text', 'file', 'card', 'question', 'reaction', 'edit', 'task_log'] }).notNull(),
    content: text('content', { mode: 'json' }).notNull(),
    status: text('status', { enum: ['queued', 'delivered', 'failed'] }).notNull(),
    attempts: integer('attempts').notNull().default(0),
    platformMessageId: text('platform_message_id'),
    deliverAfter: integer('deliver_after', { mode: 'timestamp_ms' }),
    createdAt: integer('created_at', { mode: 'timestamp_ms' }).notNull(),
  },
  (t) => [uniqueIndex('outbound_seq').on(t.sessionId, t.seq), index('outbound_queued').on(t.status)],
)

/** SDK continuation, reply route, etc. Was outbound.db session_state. */
export const sessionState = sqliteTable(
  'session_state',
  {
    sessionId: text('session_id')
      .notNull()
      .references(() => session.id, { onDelete: 'cascade' }),
    key: text('key').notNull(),
    value: text('value').notNull(),
  },
  (t) => [primaryKey({ columns: [t.sessionId, t.key] })],
)

/**
 * One row per live container incarnation. Its Session Token is the container's only credential, for both
 * the proxy and the RPC on the Agent Port. Deleting the row revokes the token (the token dies with the
 * container, not with the host process).
 */
export const container = sqliteTable(
  'container',
  {
    id: text('id').primaryKey(), // ctr-<uuidv7>; also the docker container name suffix and label
    sessionId: text('session_id')
      .notNull()
      .references(() => session.id, { onDelete: 'cascade' }),
    /** sha256 of the Session Token. The plaintext exists only in the container env. */
    tokenHash: blob('token_hash', { mode: 'buffer' }).notNull().unique(),
    status: text('status', { enum: ['starting', 'running', 'stopping'] }).notNull(),
    image: text('image').notNull(),
    startedAt: integer('started_at', { mode: 'timestamp_ms' }).notNull(),
    /** Last pull/heartbeat; replaces nanoclaw's /workspace/.heartbeat mtime. */
    lastSeenAt: integer('last_seen_at', { mode: 'timestamp_ms' }),
    currentTool: text('current_tool'),
    toolDeadlineAt: integer('tool_deadline_at', { mode: 'timestamp_ms' }),
  },
  (t) => [
    // at most one live incarnation per session; a respawn first deletes (revokes) the old one
    uniqueIndex('container_one_per_session').on(t.sessionId).where(sql`status in ('starting','running')`),
  ],
)

/** Blocking ask_user_question in flight; the click writes an `answer` inbound row. */
export const pendingQuestion = sqliteTable('pending_question', {
  id: text('id').primaryKey(),
  sessionId: text('session_id')
    .notNull()
    .references(() => session.id, { onDelete: 'cascade' }),
  outboundMessageId: text('outbound_message_id').notNull(),
  options: text('options', { mode: 'json' }).notNull(),
  createdAt: integer('created_at', { mode: 'timestamp_ms' }).notNull(),
})

/** Routing audit (nanoclaw unregistered_senders + recordDroppedMessage). */
export const droppedMessage = sqliteTable('dropped_message', {
  channelKind: text('channel_kind').notNull(),
  platformId: text('platform_id').notNull(),
  reason: text('reason').notNull(),
  count: integer('count').notNull(),
  lastAt: integer('last_at', { mode: 'timestamp_ms' }).notNull(),
})

/** Agent-to-agent hold policy per pair (nanoclaw agent_message_policies). */
export const agentMessagePolicy = sqliteTable('agent_message_policy', {
  fromAgentGroupId: text('from_agent_group_id').notNull(),
  toAgentGroupId: text('to_agent_group_id').notNull(),
  approverUserId: text('approver_user_id'),
})
